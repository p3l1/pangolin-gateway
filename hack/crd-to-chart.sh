#!/bin/sh
# Wraps controller-gen's CRDs into one chart template, adding the chart's labels
# and the optional resource-policy annotation that keeps them on uninstall.
set -eu

bases=$1
chart_crds=$2

{
	echo '# Generated by `just generate` from config/crd/bases; do not edit by hand.'
	echo '{{- if .Values.crds.install }}'
	for crd in "$bases"/*.yaml; do
		# Rewrites only the first metadata block, which is the CRD's own.
		awk '
			!done && /^metadata:$/ { print; print "  labels:"; print "    {{- include \"pangolin-gateway.labels\" . | nindent 4 }}"; next }
			!done && /^  annotations:$/ {
				print
				print "    {{- if .Values.crds.keep }}"
				print "    helm.sh/resource-policy: keep"
				print "    {{- end }}"
				done = 1
				next
			}
			{ print }
		' "$crd"
	done
	echo '{{- end }}'
} > "$chart_crds.tmp"
mv "$chart_crds.tmp" "$chart_crds"
